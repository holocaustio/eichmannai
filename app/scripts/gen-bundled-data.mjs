// Prepares the data the API routes read at runtime, because Cloudflare Workers have
// no filesystem. Runs automatically before `next build`.
//  - Transcripts (downloads/pdf/OCR_clean, ~19 MB, Git LFS) are copied to public/ocr/
//    and served as static assets; they are loaded on demand, one file at a time.
//  - Small files (entities.json) and the transcript size manifest are bundled as code.
// NOTE: the transcripts are Git LFS files - run `git lfs pull` before building.
import { readdirSync, readFileSync, writeFileSync, mkdirSync, copyFileSync, statSync } from 'node:fs';
import { join } from 'node:path';

const OCR_DIR = join('..', 'downloads', 'pdf', 'OCR_clean');
const OUT_DIR = join('public', 'ocr');
mkdirSync(OUT_DIR, { recursive: true });

const sizes = {};
for (const name of readdirSync(OCR_DIR)) {
  if (!name.endsWith('.txt')) continue;
  const src = join(OCR_DIR, name);
  if (readFileSync(src).subarray(0, 40).toString().startsWith('version https://git-lfs')) {
    throw new Error(`${src} is a Git LFS pointer - run "git lfs pull" first`);
  }
  copyFileSync(src, join(OUT_DIR, name));
  sizes[name] = statSync(src).size;
}

const bundled = { 'public/data/entities.json': readFileSync(join('public', 'data', 'entities.json'), 'utf8') };

mkdirSync(join('src', 'generated'), { recursive: true });
writeFileSync(
  join('src', 'generated', 'bundled-data.ts'),
  '// Generated by scripts/gen-bundled-data.mjs - do not edit.\n' +
    `export const OCR_SIZES: Record<string, number> = ${JSON.stringify(sizes)};\n` +
    `export const BUNDLED_FILES: Record<string, string> = ${JSON.stringify(bundled)};\n`
);
console.log(`prepared ${Object.keys(sizes).length} transcripts + ${Object.keys(bundled).length} bundled files`);
